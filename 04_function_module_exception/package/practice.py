# Objective

# Create a Python package named `geometry` that contains three modules for calculating the areas of different geometric shapes.

# ## 1. Package Structure

# Create the following folder and file structure:

# project/
# │
# ├── geometry/
# │   ├── __init__.py
# │   ├── circle.py
# │   ├── rectangle.py
# │   └── triangle.py
# │

# ## 2. Requirements

# ### A. circle.py
# - Create a function called `calculate_area(radius)`.
# - Calculate and return the area of a circle.
# - Use π (pi) in your calculation.
# - Import the `math` module to access `math.pi`.

# Formula: Area = π × radius²

# ### B. rectangle.py
# - Create a function called `calculate_area(length, width)`.
# - Calculate and return the area of a rectangle.

# Formula: Area = length × width

# ### C. triangle.py
# - Create a function called `calculate_area(base, height)`.
# - Calculate and return the area of a triangle.

# Formula: Area = ½ × base × height

# ## 3. Import and Use the Package

# 1. Import all three modules from the `geometry` package.
# 2. Call each module's `calculate_area()` function.
# 3. Provide sample values for each shape.
# 4. Display the calculated areas using `print()`.

# ## 4. Expected Output

# 
# Circle Area: 78.54
# Rectangle Area: 50
